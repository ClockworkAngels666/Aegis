"use client";

import { DownloadSimpleIcon, FileTextIcon, PrinterIcon, SpinnerGapIcon } from "@phosphor-icons/react";
import { createPortal } from "react-dom";
import { Button } from "@/components/ui/button";
import { Panel } from "@/components/panel";
import type { Memo } from "@/lib/types";

const SEVERITY_INK: Record<Memo["findings"][number]["severity"], string> = {
  critical: "#b42318",
  high: "#c2410c",
  medium: "#a16207",
  info: "#57534e",
};

function MemoDocument({ m }: { m: Memo }) {
  return (
    <article className="bg-white px-8 py-7 font-sans text-[12.5px] leading-[1.55] text-[#151515] print:bg-white print:p-0">
      <div className="flex items-center justify-between border-b-2 border-[#151515] pb-2 font-mono text-[10px] uppercase tracking-[0.18em]">
        <span>{m.marking}</span>
        <span>Ref {m.ref} · {m.date}</span>
      </div>
      <h3 className="mt-4 text-xl font-bold">{m.title}</h3>
      <p className="mt-1 text-[#444]"><b className="text-[#151515]">Subject:</b> {m.subject}</p>

      <div className="mt-4 border-l-4 py-1 pl-3" style={{ borderColor: m.verdict.level >= 3 ? "#b42318" : m.verdict.level === 2 ? "#c2410c" : "#15803d" }}>
        <div className="font-mono text-[11px] font-bold uppercase tracking-[0.14em] text-[#444]">Bottom line</div>
        <p className="font-semibold">{m.bluf}</p>
        <p className="mt-1 font-mono text-[11px] text-[#444]">
          Route risk {m.scores.route}/100 {m.scores.route_band} · Sanctions screening {m.scores.entity}/100 {m.scores.entity_status}
        </p>
      </div>

      {m.narrative && (
        <section className="mt-4">
          <h4 className="memo-h">Analyst assessment</h4>
          <p>{m.narrative}</p>
        </section>
      )}

      <section className="mt-4">
        <h4 className="memo-h">Key findings</h4>
        <ul className="space-y-1">
          {m.findings.map((f) => (
            <li key={f.text} className="flex gap-2">
              <span className="mt-[3px] w-24 shrink-0 font-mono text-[9.5px] font-semibold uppercase tracking-wider"
                style={{ color: SEVERITY_INK[f.severity] }}>{f.area}</span>
              <span>{f.text}</span>
            </li>
          ))}
        </ul>
      </section>

      <section className="mt-4">
        <h4 className="memo-h">Legal exposure</h4>
        <ul className="list-disc space-y-1 pl-4">{m.legal.map((x) => <li key={x}>{x}</li>)}</ul>
      </section>

      <section className="mt-4">
        <h4 className="memo-h">Recommended enhanced due diligence</h4>
        <ol className="list-decimal space-y-1 pl-4">{m.edd.map((x) => <li key={x}>{x}</li>)}</ol>
      </section>

      <section className="mt-4 text-[11px] text-[#444]">
        <h4 className="memo-h">Limitations</h4>
        <ul className="list-disc space-y-0.5 pl-4">{m.limitations.map((x) => <li key={x}>{x}</li>)}</ul>
      </section>

      <footer className="mt-4 border-t border-[#ccc] pt-2 font-mono text-[9.5px] leading-relaxed text-[#666]">
        Sources: {m.sources.map((s) => s.label).join(" · ")}
        <br />
        Generated by Aegis ({m.engine === "rules" ? "rule-based engine" : "rule-based engine + language model narrative"}).
      </footer>
    </article>
  );
}

export function MemoPanel({ memo, loading, error, onGenerate, stale }: {
  memo: Memo | null;
  loading: boolean;
  error: string | null;
  onGenerate: () => void;
  stale: boolean;
}) {
  const download = () => {
    if (!memo) return;
    const url = URL.createObjectURL(new Blob([memo.markdown], { type: "text/markdown" }));
    const a = Object.assign(document.createElement("a"), { href: url, download: `${memo.ref}.md` });
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <Panel
      title="Briefing"
      subtitle="One-page compliance summary for the file."
      action={
        memo && !stale ? (
          <div className="flex gap-1.5">
            <Button size="xs" variant="outline" onClick={() => window.print()}><PrinterIcon /> Print / PDF</Button>
            <Button size="xs" variant="outline" onClick={download}><DownloadSimpleIcon /> Markdown</Button>
          </div>
        ) : null
      }
    >
      {memo && !stale ? (
        <div className="max-h-[720px] overflow-y-auto bg-muted p-3 sm:p-5"><div className="mx-auto max-w-[820px] shadow-[0_1px_3px_rgba(16,24,40,0.12)] ring-1 ring-border">
          <MemoDocument m={memo} />
        </div></div>
      ) : (
        <div className="flex flex-col items-center gap-3 py-8 text-center">
          <FileTextIcon className="size-8 text-faint" />
          <p className="max-w-md font-sans text-[13px] text-muted-foreground">
            Findings, legal exposure under the AWG and Reg. 833/2014, and due-diligence steps on one page.
          </p>
          <Button onClick={onGenerate} disabled={loading}>
            {loading ? <SpinnerGapIcon className="animate-spin" /> : <FileTextIcon />}
            {loading ? "Drafting…" : "Generate briefing"}
          </Button>
          {error && <p className="text-[11px] text-destructive">{error}</p>}
        </div>
      )}
      {memo && !stale && typeof document !== "undefined" && createPortal(<div id="memo-print"><MemoDocument m={memo} /></div>, document.body)}
    </Panel>
  );
}
